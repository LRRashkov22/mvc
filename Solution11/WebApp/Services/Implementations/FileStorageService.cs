using System.Text.RegularExpressions;
using Microsoft.Extensions.Options;
using SixLabors.ImageSharp;
using SixLabors.ImageSharp.Formats.Webp;
using SixLabors.ImageSharp.Processing;
using WebApplication1.Services.Contracts;

namespace WebApplication1.Services.Implementations;

public sealed class FileStorageService : IFileStorageService
{
    private static readonly HashSet<string> AllowedExtensions =
        new(StringComparer.OrdinalIgnoreCase) { ".jpg", ".jpeg", ".png", ".webp" };

    private static readonly HashSet<string> AllowedContentTypes =
        new(StringComparer.OrdinalIgnoreCase) { "image/jpeg", "image/png", "image/webp" };

    // Only names generated by this service are ever read or deleted.
    private static readonly Regex SafeFileName =
        new(@"^[a-f0-9]{32}(_thumb)?\.webp$", RegexOptions.Compiled);

    private readonly FileStorageOptions _options;
    private readonly string _root;

    public FileStorageService(IOptions<FileStorageOptions> options, IWebHostEnvironment env)
    {
        _options = options.Value;

        var configured = _options.RootPath;
        var combined = Path.IsPathRooted(configured)
            ? configured
            : Path.Combine(env.ContentRootPath, configured);

        _root = Path.TrimEndingDirectorySeparator(Path.GetFullPath(combined));
        Directory.CreateDirectory(_root);
    }

    public async Task<StoredImage> SaveImageAsync(IFormFile file, string subFolder, CancellationToken ct = default)
    {
        ValidateFile(file);

        await using var buffer = new MemoryStream();
        await file.CopyToAsync(buffer, ct);

        if (buffer.Length > _options.MaxFileSizeBytes)
            throw new FileValidationException(SizeMessage());

        // Check the real content, not just the extension or the client-supplied content type.
        var header = new byte[12];
        buffer.Position = 0;
        var read = await buffer.ReadAsync(header, 0, header.Length, ct);
        if (!HasImageSignature(header, read))
            throw new FileValidationException("The file content is not a valid JPEG, PNG or WebP image.");
        buffer.Position = 0;

        var folder = ResolveFolder(subFolder);
        Directory.CreateDirectory(folder);

        var id = Guid.NewGuid().ToString("N");
        var fileName = $"{id}.webp";
        var thumbName = $"{id}_thumb.webp";
        var mainPath = Path.Combine(folder, fileName);
        var thumbPath = Path.Combine(folder, thumbName);

        try
        {
            var info = await Image.IdentifyAsync(buffer, ct);
            if ((long)info.Width * info.Height > _options.MaxPixels)
                throw new FileValidationException("The image dimensions are too large.");

            buffer.Position = 0;
            using var image = await Image.LoadAsync(buffer, ct);

            // Apply the camera rotation, then drop metadata (EXIF can contain GPS location).
            image.Mutate(x => x.AutoOrient());
            image.Metadata.ExifProfile = null;
            image.Metadata.XmpProfile = null;
            image.Metadata.IptcProfile = null;

            var max = _options.MaxImageDimension;
            if (image.Width > max || image.Height > max)
            {
                image.Mutate(x => x.Resize(new ResizeOptions
                {
                    Size = new Size(max, max),
                    Mode = ResizeMode.Max
                }));
            }

            await image.SaveAsync(mainPath, new WebpEncoder
            {
                Quality = _options.WebpQuality,
                FileFormat = WebpFileFormatType.Lossy
            }, ct);

            var t = _options.ThumbnailSize;
            using var thumb = image.Clone(x =>
            {
                if (image.Width > t || image.Height > t)
                {
                    x.Resize(new ResizeOptions { Size = new Size(t, t), Mode = ResizeMode.Max });
                }
            });

            await thumb.SaveAsync(thumbPath, new WebpEncoder
            {
                Quality = Math.Min(70, _options.WebpQuality),
                FileFormat = WebpFileFormatType.Lossy
            }, ct);

            return new StoredImage(
                fileName,
                thumbName,
                SanitizeOriginalName(file.FileName),
                new FileInfo(mainPath).Length,
                image.Width,
                image.Height);
        }
        catch (Exception ex) when (ex is UnknownImageFormatException
                                       or InvalidImageContentException
                                       or NotSupportedException)
        {
            DeleteIfExists(mainPath, thumbPath);
            throw new FileValidationException("The file is corrupt or is not a supported image.");
        }
        catch
        {
            DeleteIfExists(mainPath, thumbPath);
            throw;
        }
    }

    public void Delete(string subFolder, params string[] fileNames)
    {
        var folder = ResolveFolder(subFolder);
        foreach (var name in fileNames)
        {
            if (!SafeFileName.IsMatch(name)) continue;
            DeleteIfExists(Path.Combine(folder, name));
        }
    }

    public void DeleteFolder(string subFolder)
    {
        var folder = ResolveFolder(subFolder);
        if (Directory.Exists(folder))
            Directory.Delete(folder, recursive: true);
    }

    public string? GetPhysicalPath(string subFolder, string fileName)
    {
        if (!SafeFileName.IsMatch(fileName)) return null;

        var path = Path.Combine(ResolveFolder(subFolder), fileName);
        return File.Exists(path) ? path : null;
    }

    // ---------- helpers ----------

    private void ValidateFile(IFormFile? file)
    {
        if (file is null || file.Length == 0)
            throw new FileValidationException("No file was uploaded or the file is empty.");

        if (file.Length > _options.MaxFileSizeBytes)
            throw new FileValidationException(SizeMessage());

        var extension = Path.GetExtension(file.FileName);
        if (string.IsNullOrEmpty(extension) || !AllowedExtensions.Contains(extension))
            throw new FileValidationException("Only JPG, PNG and WebP images are allowed.");

        if (!AllowedContentTypes.Contains(file.ContentType))
            throw new FileValidationException("Only JPG, PNG and WebP images are allowed.");
    }

    private string SizeMessage() =>
        $"The file is larger than {_options.MaxFileSizeBytes / (1024 * 1024)} MB.";

    private static bool HasImageSignature(byte[] h, int length)
    {
        if (length < 12) return false;

        // JPEG: FF D8 FF
        if (h[0] == 0xFF && h[1] == 0xD8 && h[2] == 0xFF) return true;

        // PNG: 89 50 4E 47 0D 0A 1A 0A
        if (h[0] == 0x89 && h[1] == 0x50 && h[2] == 0x4E && h[3] == 0x47 &&
            h[4] == 0x0D && h[5] == 0x0A && h[6] == 0x1A && h[7] == 0x0A) return true;

        // WebP: "RIFF" .... "WEBP"
        if (h[0] == 'R' && h[1] == 'I' && h[2] == 'F' && h[3] == 'F' &&
            h[8] == 'W' && h[9] == 'E' && h[10] == 'B' && h[11] == 'P') return true;

        return false;
    }

    private string ResolveFolder(string subFolder)
    {
        var full = Path.GetFullPath(Path.Combine(_root, subFolder));
        if (!full.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new InvalidOperationException("Invalid storage path.");
        return full;
    }

    private static string SanitizeOriginalName(string name)
    {
        var clean = new string(Path.GetFileName(name).Where(c => !char.IsControl(c)).ToArray());
        return clean.Length > 100 ? clean[..100] : clean;
    }

    private static void DeleteIfExists(params string[] paths)
    {
        foreach (var path in paths)
        {
            try
            {
                if (File.Exists(path)) File.Delete(path);
            }
            catch (IOException) { /* best effort */ }
            catch (UnauthorizedAccessException) { /* best effort */ }
        }
    }
}